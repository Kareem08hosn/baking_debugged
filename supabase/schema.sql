create policy "people can delete their own notes"
  on public.recipe_notes for delete to authenticated
  using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Preferences: one row per person.
-- ---------------------------------------------------------------------------
create table public.preferences (
  user_id uuid primary key default auth.uid()
    references auth.users (id) on delete cascade,
  -- the ids lib/units.js uses: grams, us (cups and spoons), ml
  unit_system text not null default 'grams' check (unit_system in ('grams', 'us', 'ml')),
  -- the diet filter /recipes starts with
  diet text not null default 'all' check (diet in ('all', 'vegetarian', 'vegan')),
  updated_at timestamptz not null default now()
);

alter table public.preferences enable row level security;
grant select, insert, update on public.preferences to authenticated;

