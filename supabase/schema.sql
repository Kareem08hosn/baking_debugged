-- Baking Debugged: database tables.
-- Run this once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Then run seed.sql to add the starter recipes.

-- One row per recipe. Column names use snake_case (prep_time), which is the
-- SQL convention; the website converts them to camelCase (prepTime).
create table public.recipes (
  -- A number the database assigns automatically: 1, 2, 3...
  id bigint generated by default as identity primary key,

  name text not null,
  category text not null,
  -- "check" makes the database refuse any other value
  difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
  prep_time integer not null check (prep_time >= 0), -- minutes
  bake_time integer not null check (bake_time >= 0), -- minutes
  servings numeric not null check (servings > 0),
  pan text, -- a pan id such as 'loaf-23x13', or null for no pan
  rating numeric check (rating between 1 and 5),

  -- text[] is a list of text values: {vegetarian,vegan}
  diet text[] not null default '{}',
  -- jsonb stores JSON as-is: [{"name": "flour", "amount": 250, "unit": "g"}, ...]
  ingredients jsonb not null,
  instructions text[] not null,

  -- where the recipe was adapted from: {"name": "King Arthur Baking", "url": "https://..."}
  -- (null for recipes people wrote themselves)
  source jsonb,
  -- true once the site owner has baked it; false shows an "Untested" badge
  tested boolean not null default false,

  -- who added it: null for the site's own recipes, otherwise the user's id
  -- (filled in automatically with whoever is signed in)
  owner uuid references auth.users (id) on delete cascade default auth.uid(),

  created_at timestamptz not null default now()
);

create index recipes_owner_idx on public.recipes (owner);

-- Row Level Security (RLS): with it on, nobody can do anything to the table
-- unless a policy below allows it.
alter table public.recipes enable row level security;

-- Reading: everyone ("anon" = not signed in, "authenticated" = signed in)
-- can read the site's recipes; people can also read their own.
-- (select auth.uid()) is the signed-in user's id, or null.
grant select on public.recipes to anon, authenticated;

create policy "anyone can read site recipes"
  on public.recipes
  for select
  to anon, authenticated
  using (owner is null);

create policy "people can read their own recipes"
  on public.recipes
  for select
  to authenticated
  using (owner = (select auth.uid()));

-- Writing: signed-in people, only on their own rows. "with check" tests the
-- new row, so nobody can add or move a recipe under someone else's id.
-- Nobody can change the site's recipes (owner is null) from the website.
grant insert, update, delete on public.recipes to authenticated;

create policy "people can add their own recipes"
  on public.recipes
  for insert
  to authenticated
  with check (owner = (select auth.uid()));

create policy "people can change their own recipes"
  on public.recipes
  for update
  to authenticated
  using (owner = (select auth.uid()))
  with check (owner = (select auth.uid()));

create policy "people can delete their own recipes"
  on public.recipes
  for delete
  to authenticated
  using (owner = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Favourites: the recipes each person has saved with the Save button.
-- ---------------------------------------------------------------------------

-- One row per (person, recipe) pair. The primary key on both columns means
-- the same recipe can't be saved twice by the same person.
create table public.favourites (
  -- who saved it: filled in automatically with whoever is signed in
  user_id uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  -- which recipe; if the recipe is deleted, its favourites go too
  recipe_id bigint not null
    references public.recipes (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, recipe_id)
);

alter table public.favourites enable row level security;

-- Signed-in people only. There is no update policy: a favourite is either
-- there or not, so it is only ever added or deleted.
grant select, insert, delete on public.favourites to authenticated;

create policy "people can see their own favourites"
  on public.favourites
  for select
  to authenticated
  using (user_id = (select auth.uid()));

-- You can only save recipes you can see. The "exists" check runs with your
-- own permissions, so someone else's private recipe doesn't count.
create policy "people can save recipes they can see"
  on public.favourites
  for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and exists (select 1 from public.recipes where recipes.id = recipe_id)
  );

create policy "people can remove their own favourites"
  on public.favourites
  for delete
  to authenticated
  using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Bakes: one row every time someone bakes something. This is the bake log
-- AND the "made it" log: a quick "I made this" on a recipe page fills in the
-- date, rating and notes; the bake log form fills in the lab measurements too.
-- ---------------------------------------------------------------------------
create table public.bakes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  -- the recipe it was made from, if any. "on delete set null" keeps the bake
  -- in the log if the recipe is deleted later.
  recipe_id bigint references public.recipes (id) on delete set null,
  -- what was baked, written out (copied from the recipe name), so the log
  -- still makes sense without the recipe
  title text not null check (char_length(title) between 1 and 120),
  baked_on date not null default current_date,
  rating numeric check (rating between 1 and 5), -- halves allowed: 3.5

  -- the measurements (all optional)
  flour_g numeric check (flour_g >= 0),
  water_g numeric check (water_g >= 0),
  sugar_g numeric check (sugar_g >= 0),
  fat_g numeric check (fat_g >= 0),
  leavener text check (char_length(leavener) <= 80),
  hydration_pct numeric check (hydration_pct between 0 and 300),
  oven_temp_c numeric check (oven_temp_c between 0 and 400),
  bake_time_min numeric check (bake_time_min between 0 and 1440),

  -- what happened (all optional)
  rise text check (char_length(rise) <= 200), -- rise for bread, spread for cookies
  texture text check (char_length(texture) <= 200),
  what_went_wrong text check (char_length(what_went_wrong) <= 2000),
  notes text check (char_length(notes) <= 2000),

  created_at timestamptz not null default now()
);

-- Makes "my bakes, newest first" fast.
create index bakes_user_date_idx on public.bakes (user_id, baked_on desc);

alter table public.bakes enable row level security;
grant select, insert, update, delete on public.bakes to authenticated;

create policy "people can see their own bakes"
  on public.bakes for select to authenticated
  using (user_id = (select auth.uid()));

-- A bake can only point at a recipe the person can see (or at none).
create policy "people can log their own bakes"
  on public.bakes for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and (recipe_id is null or exists (select 1 from public.recipes where recipes.id = recipe_id))
  );

create policy "people can change their own bakes"
  on public.bakes for update to authenticated
  using (user_id = (select auth.uid()))
  with check (
    user_id = (select auth.uid())
    and (recipe_id is null or exists (select 1 from public.recipes where recipes.id = recipe_id))
  );

create policy "people can delete their own bakes"
  on public.bakes for delete to authenticated
  using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Recipe notes: one private note per person per recipe.
-- ---------------------------------------------------------------------------
create table public.recipe_notes (
  user_id uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 5000),
  updated_at timestamptz not null default now(),
  primary key (user_id, recipe_id)
);

alter table public.recipe_notes enable row level security;
grant select, insert, update, delete on public.recipe_notes to authenticated;

create policy "people can see their own notes"
  on public.recipe_notes for select to authenticated
  using (user_id = (select auth.uid()));

create policy "people can write notes on recipes they can see"
  on public.recipe_notes for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and exists (select 1 from public.recipes where recipes.id = recipe_id)
  );

create policy "people can change their own notes"
  on public.recipe_notes for update to authenticated
  using (user_id = (select auth.uid()))
